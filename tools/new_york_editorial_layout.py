def captions(d):
 assert len(CAPTIONS)==130
 for b in d['blocks']:
  if b['kind']!='figure':continue
  i=b['id'];original=b['caption']
  credit='画作 / LeRoy Neiman，1983' if i==57 else ('摄影 / MarathonFoto' if 'MarathonFoto' in original else '摄影 / Arsenan')
  b['alt']=CAPTIONS[i-1]
  b['caption']=CAPTIONS[i-1]+' · '+credit

def arrange(d):
 images={b['id']:b for b in d['blocks'] if b['kind']=='figure'}
 result=[];ci=-1;pi=0
 for b in d['blocks']:
  if b['kind']=='heading':
   ci+=1;pi=0;result.append(b);continue
  if b['kind']=='figure':continue
  photos=[images[i] for i in POSITIONS[ci].get(pi,[])]
  sentences=re.findall(r'.*?[。！？](?:[”’])?|.+$',b['text'])
  count=max(1,(len(photos)+2)//3)
  if len(sentences)<count:
   sentences=re.findall(r'.*?[，。！？；](?:[”’])?|.+$',b['text'])
  count=min(count,len(sentences))
  cuts=[round(k*len(sentences)/count) for k in range(count+1)]
  pics=[round(k*len(photos)/count) for k in range(count+1)]
  for k in range(count):
   parts=[];chunk=''
   for sentence in sentences[cuts[k]:cuts[k+1]]:
    if chunk and len(chunk)+len(sentence)>130:parts.append(chunk);chunk=''
    chunk+=sentence
   if chunk:parts.append(chunk)
   for t in parts:result.append({'kind':'paragraph','text':t,'original_html':'<p>'+escape(t)+'</p>'})
   result.extend(photos[pics[k]:pics[k+1]])
  pi+=1
 ids=[b['id'] for b in result if b['kind']=='figure']
 assert len(ids)==len(set(ids))==130,(len(ids),set(images)-set(ids))
 assert ''.join(b['text'] for b in result if b['kind']=='paragraph')==''.join(d['original_paragraphs'])
 return result
